# Descripció: Calcula la suma dels primers 100 nombres enters positius (de 1 a 100) i mostra el resultat.
# Especificacions d'Entrada: Programa que et sumi els primers 100 nombres esnters i els mostri el resultat.

numero = 0

resultat = 1

while(resultat <= 100):
    numero += resultat
    resultat += 1

print(numero)